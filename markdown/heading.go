// headingRenderer replaces the default heading rendering: keeps the
// parser-generated slug id (or a "# Heading {#id}" override) and appends a
// hover permalink anchor.
type headingRenderer struct{}

func (h *headingRenderer) RegisterFuncs(reg renderer.NodeRendererFuncRegisterer) {
	reg.Register(ast.KindHeading, h.render)
}

func (h *headingRenderer) render(w util.BufWriter, source []byte, n ast.Node, entering bool) (ast.WalkStatus, error) {
	hn := n.(*ast.Heading)
	if entering {
		fmt.Fprintf(w, "<h%d", hn.Level)
		htmlrenderer.RenderAttributes(w, n, htmlrenderer.HeadingAttributeFilter)
		w.WriteByte('>')
		return ast.WalkContinue, nil
	}
	if v, ok := n.Attribute([]byte("id")); ok {
		var idStr string
		switch id := v.(type) {
		case []byte:
			idStr = string(id)
		case string:
			idStr = id
		}
		if idStr != "" {
			fmt.Fprintf(w, `<a class="heading-anchor" href="#%s" aria-label="Link to this section">#</a>`,
				stdhtml.EscapeString(idStr))
		}
	}
	fmt.Fprintf(w, "</h%d>\n", hn.Level)
	return ast.WalkContinue, nil
}

// headingIDTransformer replaces parser.WithAutoHeadingID. It runs after
// inline parsing (priority just above the alertTransformer) so the slug
// is computed from the heading's rendered text, not its source: a link's
// URL and markup drop out ("#### [Release Notes](#release-notes)"
// becomes "release-notes", not "release-notesrelease-notes"). A
// "{#custom}" id parsed from the source always wins — the transformer
// only fills empty ones — but it reserves the id too, because dropping
// the auto option also drops goldmark's Close, which used to register
// custom ids; without that, "# A {#foo}" plus "# foo" would both get
// "foo". Dedup stays per-document: the used set lives in the parse
// context, which spans one Parse.
type headingIDTransformer struct{}

var headingIDsKey = parser.NewContextKey()

func (headingIDTransformer) Transform(doc *ast.Document, reader text.Reader, pc parser.Context) {
	used, _ := pc.Get(headingIDsKey).(map[string]bool)
	if used == nil {
		used = map[string]bool{}
		pc.Set(headingIDsKey, used)
	}
	source := reader.Source()
	_ = ast.Walk(doc, func(n ast.Node, entering bool) (ast.WalkStatus, error) {
		if !entering {
			return ast.WalkContinue, nil
		}
		h, ok := n.(*ast.Heading)
		if !ok {
			return ast.WalkContinue, nil
		}
		if id, ok := attrString(h.AttributeString("id")); ok && id != "" {
			reserveID(used, pc, id)
			return ast.WalkContinue, nil
		}
		// goldmark's empty-slug fallback, kept identical.
		base := slug(headingText(h, source))
		if base == "" {
			base = "heading"
		}
		id := base
		for i := 1; used[id]; i++ {
			id = base + "-" + strconv.Itoa(i)
		}
		reserveID(used, pc, id)
		h.SetAttribute([]byte("id"), []byte(id))
		return ast.WalkContinue, nil
	})
}

// reserveID records id in the transformer's used set and in goldmark's
// own ID pool, so footnote ids (generated by the footnote transformer at
// a later priority, through the same pool) can never collide with a
// heading id.
func reserveID(used map[string]bool, pc parser.Context, id string) {
	used[id] = true
	pc.IDs().Put([]byte(id))
}

// attrString normalizes an attribute value, which goldmark stores either
// as []byte or string depending on who set it.
func attrString(v any, ok bool) (string, bool) {
	if !ok {
		return "", false
	}
	switch s := v.(type) {
	case []byte:
		return string(s), true
	case string:
		return s, true
	}
	return "", false
}
